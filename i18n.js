function defaultLang() {
    return /^vi\b/i.test(globalThis.navigator?.language || '') ? 'vi' : 'en';
}

let currentLang = defaultLang();

function setLang(lang) {
    currentLang = STRINGS[lang] ? lang : defaultLang();
}

function getLang() {
    return currentLang;
}

// Placeholders like {name} are filled in. The result is plain text: callers put it in textContent, never innerHTML.
function t(key, vars = {}) {
    const text = STRINGS[currentLang][key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// Fill elements marked with data-i18n, data-i18n-placeholder, data-i18n-title and data-i18n-aria
function applyI18n(root) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    if (root.documentElement) root.documentElement.lang = currentLang;
}
